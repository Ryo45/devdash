"""Offline, deterministic bundles. Atomic current switch; never applies systemd units."""

import difflib
import fcntl
import hashlib
import json
import os
import re
import shutil
import tempfile
import uuid
from pathlib import Path

import yaml

from .model import Config

OWNER = "devdash-stage-generator-v1\n"
STORE = ".devdash-generated"


def digest(data):
    return hashlib.sha256(data.encode()).hexdigest()


def render(config):
    config = Config(config.json())
    files = {"devdash.yaml": yaml.safe_dump(config.json(), sort_keys=True, allow_unicode=True)}
    for key, prerequisites in sorted(config.dependencies.items()):
        if not prerequisites:
            continue
        work = config.workloads[key]
        units = " ".join(sorted(config.workloads[p]["unit"] for p in prerequisites))
        files[f"systemd/{work['scope']}/{work['unit']}.d/60-devdash-stage-dependencies.conf"] = (
            "# Generated by devdash; owns this drop-in only. Do not edit.\n[Unit]\n"
            f"Requisite={units}\nAfter={units}\n"
        )
    return dict(sorted(files.items()))


def read_current(root):
    root = Path(root)
    if root.is_symlink():
        raise ValueError("Output root must not be a symlink")
    store, current = root / STORE, root / "current"
    if store.exists() or store.is_symlink():
        if (
            store.is_symlink()
            or not store.is_dir()
            or (store / "OWNER").is_symlink()
            or (store / "OWNER").read_text() != OWNER
        ):
            raise ValueError("Generator store is not owned by devdash")
    if not current.exists() and not current.is_symlink():
        return None, {}
    if not current.is_symlink() or not re.fullmatch(
        r"\.devdash-generated/[a-f0-9]{64}", os.readlink(current)
    ):
        raise ValueError("current is unrelated to this generator; refusing overwrite")
    name = Path(os.readlink(current)).name
    bundle = store / name
    if bundle.is_symlink() or not bundle.is_dir():
        raise ValueError("Invalid generated bundle")
    manifest = bundle / ".manifest.json"
    if manifest.is_symlink():
        raise ValueError("Symlink in generated manifest")
    hashes = json.loads(manifest.read_text())
    if not isinstance(hashes, dict) or not all(
        isinstance(key, str) and isinstance(value, str) and re.fullmatch(r"[a-f0-9]{64}", value)
        for key, value in hashes.items()
    ):
        raise ValueError("Invalid generated manifest")
    files = {}
    actual = set()
    for path in bundle.rglob("*"):
        if path.is_symlink():
            raise ValueError("Symlink in generated bundle")
        if path.is_file() and path != manifest:
            actual.add(path.relative_to(bundle).as_posix())
    if actual != set(hashes):
        raise ValueError("Generated file set was edited; preserve changes before generating")
    for path, expected in hashes.items():
        value = (bundle / path).read_text()
        if digest(value) != expected:
            raise ValueError("Generated file was edited: " + path)
        files[path] = value
    if digest(json.dumps(files, sort_keys=True)) != name:
        raise ValueError("Bundle identity does not match contents")
    return name, files


def preview(config, root):
    previous, old = read_current(root)
    files = render(config)
    changes = []
    for path in sorted(old.keys() | files.keys()):
        before, after = old.get(path, ""), files.get(path, "")
        action = (
            "unchanged"
            if before == after
            else "create"
            if path not in old
            else "remove"
            if path not in files
            else "modify"
        )
        changes.append(
            dict(
                path=path,
                action=action,
                diff="".join(
                    difflib.unified_diff(
                        before.splitlines(True),
                        after.splitlines(True),
                        fromfile="old/" + path,
                        tofile="new/" + path,
                    )
                ),
            )
        )
    return dict(
        previous=previous,
        generation=digest(json.dumps(files, sort_keys=True)),
        files=files,
        changes=changes,
    )


def generate(config, root):
    root = Path(root)
    read_current(root)  # Refuse unrelated paths before any writes.
    root.mkdir(parents=True, exist_ok=True)
    store = root / STORE
    if not store.exists():
        store.mkdir()
        (store / "OWNER").write_text(OWNER)
    if (store / ".lock").is_symlink():
        raise ValueError("Generator lock must not be a symlink")
    with (store / ".lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        plan = preview(config, root)
        bundle = store / plan["generation"]
        if not bundle.exists():
            staging = Path(tempfile.mkdtemp(prefix=".pending-", dir=store))
            try:
                for path, value in plan["files"].items():
                    target = staging / path
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(value)
                (staging / ".manifest.json").write_text(
                    json.dumps(
                        {path: digest(value) for path, value in plan["files"].items()},
                        sort_keys=True,
                    )
                )
                Config.load(staging / "devdash.yaml")
                staging.rename(bundle)
            finally:
                if staging.exists():
                    shutil.rmtree(staging)
        # Check a reused bundle too; changed immutable generations are never reused.
        link = root / (".current-" + uuid.uuid4().hex)
        try:
            link.symlink_to(f"{STORE}/{plan['generation']}")
            # Validate target before publishing, without trusting an old manifest.
            if bundle.is_symlink():
                raise ValueError("Bundle must not be a symlink")
            expected_hashes = {path: digest(value) for path, value in plan["files"].items()}
            if (bundle / ".manifest.json").is_symlink() or json.loads(
                (bundle / ".manifest.json").read_text()
            ) != expected_hashes:
                raise ValueError("Generated manifest was edited")
            actual = {
                p.relative_to(bundle).as_posix(): p.read_text()
                for p in bundle.rglob("*")
                if p.is_file() and p.name != ".manifest.json"
            }
            if (
                bundle.is_symlink()
                or any(p.is_symlink() for p in bundle.rglob("*"))
                or actual != plan["files"]
            ):
                raise ValueError("Existing generated bundle was edited")
            os.replace(link, root / "current")
        finally:
            link.unlink(missing_ok=True)
        return plan


def save_source(path, config, expected=None):
    """Save an explicitly selected source; reject stale edits and symlinks."""
    config = Config(config.json())
    path = Path(path)
    if STORE in path.resolve().parts:
        raise ValueError("Generated runtime bundles are read-only; edit the source model instead")
    if path.is_symlink():
        raise ValueError("Source path must not be a symlink")
    existing = path.read_text() if path.exists() else None
    if existing != expected:
        raise ValueError("Source changed on disk or already exists; reopen before overwriting")
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(config.json(), sort_keys=False, allow_unicode=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".devdash-source-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as output:
            output.write(text)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)
    return text
